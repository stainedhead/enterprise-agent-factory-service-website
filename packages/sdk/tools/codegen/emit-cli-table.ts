import type { Contract, Node, OperationIR } from "./ir.js";
import { SECRET_FIELDS } from "./secret-fields.js";

const HEADER = "// Code generated by tools/codegen from contract/openapi.yaml; DO NOT EDIT.\n";

/** `teamId` → `team-id`; `maxBudgetUsd` → `max-budget-usd`. */
export const kebab = (s: string): string =>
  s
    .replace(/([GMK]i)B\b/g, "$1b") // scratchSizeGiB -> scratch-size-gib
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

type Kind = "scalar" | "list" | "json";

function makeDeref(c: Contract): (n: Node) => Node {
  return (n) => {
    let cur = n;
    for (let i = 0; i < 20 && cur && typeof cur.$ref === "string"; i++)
      cur = c.schemas[cur.$ref.split("/").pop() as string];
    return cur;
  };
}

function kindOf(schema: Node, deref: (n: Node) => Node): Kind {
  const s = deref(schema) ?? {};
  const t = Array.isArray(s.type) ? s.type.find((x: string) => x !== "null") : s.type;
  if (t === "array") {
    const it = deref(s.items) ?? {};
    const itT = Array.isArray(it.type) ? it.type.find((x: string) => x !== "null") : it.type;
    return itT && itT !== "object" && itT !== "array" ? "list" : "json";
  }
  if (t === "object" || s.properties || s.oneOf || s.anyOf || s.allOf) return "json";
  return "scalar";
}

interface Field {
  name: string;
  flag: string;
  kind: Kind;
  required: boolean;
  secret?: boolean;
}

function bodyFields(o: OperationIR, deref: (n: Node) => Node): Field[] {
  const schema = deref(o.requestBody?.schema);
  const props: Record<string, Node> = schema?.properties ?? {};
  const required = new Set<string>(schema?.required ?? []);
  return Object.entries(props)
    .filter(([, p]) => !deref(p as Node)?.readOnly && !(p as Node)?.readOnly)
    .map(([name, p]) => ({
      name,
      flag: kebab(name),
      kind: kindOf(p, deref),
      required: required.has(name),
      // only credentials are CLI secrets; a write-only reason or note is an ordinary flag
      ...(SECRET_FIELDS[o.operationId]?.includes(name) && { secret: true }),
    }));
}

/**
 * The CLI preview table (WD-17): operationId → `x-afs-cli` service and operation, with a flag per path,
 * query and body field (kebab-case) and which of them are lists, JSON or secrets. Console previews are
 * built from it, so they can never drift from the operation's field names.
 */
export function emitCliTable(c: Contract): string {
  const deref = makeDeref(c);
  const entries = [...c.operations]
    .filter((o) => o.cli && !o.cli.startsWith("none"))
    .sort((a, b) => a.operationId.localeCompare(b.operationId))
    .map((o) => {
      const [service, operation] = o.cli.trim().split(/\s+/);
      const e = {
        service,
        operation,
        path: o.pathParams.map((p) => ({ name: p, flag: kebab(p) })),
        query: o.queryParams.map((p) => ({ name: p.name, flag: kebab(p.name) })),
        body: bodyFields(o, deref),
      };
      return `  ${o.operationId}: ${JSON.stringify(e)},`;
    });
  return `${HEADER}/** How an operation's field is passed on the \`afs\` command line. */
export interface CliField {
  readonly name: string;
  readonly flag: string;
  /** \`list\`: space-separated values; \`json\`: a JSON document; otherwise one scalar. */
  readonly kind?: "scalar" | "list" | "json";
  readonly required?: boolean;
  /** Never rendered: the command shows a \`file://<path>\` placeholder. */
  readonly secret?: boolean;
}

export interface CliOperation {
  readonly service: string;
  readonly operation: string;
  readonly path: readonly CliField[];
  readonly query: readonly CliField[];
  readonly body: readonly CliField[];
}

/** Every CLI operation of the contract, keyed by operationId. */
export const cliOperations: Readonly<Record<string, CliOperation>> = {
${entries.join("\n")}
};
`;
}
