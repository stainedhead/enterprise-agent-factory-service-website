import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { CONTRACT_DIR } from "../contract-sync.js";
import { emitSchemas } from "./emit-schemas.js";
import { diffGenerated, generate } from "./index.js";
import { loadContract } from "./loader.js";

const c = loadContract(CONTRACT_DIR);
const out = emitSchemas(c);
const block = (name: string) => {
  const start = out.search(new RegExp(`export (interface|type) ${name}\\b`));
  return out.slice(start, out.indexOf("\n}\n", start) + 3);
};

describe("schema emitter (M0-G2)", () => {
  it("brands Money and never types a money field as number", () => {
    expect(out).toContain("export type Money = string & {");
    const moneyFields = [...out.matchAll(/(\w*(?:Usd|Amount)\w*)\??: (number)/g)];
    expect(moneyFields).toEqual([]);
    expect(block("Budget")).not.toMatch(/Usd\??: number/);
  });
  it("marks readOnly fields readonly and omits them from Input types", () => {
    const team = block("Team");
    expect(team).toContain("readonly id: string;");
    expect(team).toContain("readonly version");
    const inputs = [...out.matchAll(/export type (\w+)Input = (\{[\s\S]*?\n\});/g)];
    for (const [, name, body] of inputs) expect(body, `${name}Input`).not.toMatch(/readonly /);
  });
  it("opens inline enums", () => {
    expect(block("Team")).toContain('"persistent" | "ephemeral" | (string & {})');
  });
  it("renders nullable oneOf as T | null", () => {
    expect(block("Team")).toContain("ceilingOverrideUsd?: Money | null;");
  });
  it("renders ResourceStatus, Me and WorkOrderRepo", () => {
    expect(block("ResourceStatus")).toContain("generation: number;");
    expect(block("Me")).toContain("servicePermissions?: string[];");
    expect(block("WorkOrderRepo")).toContain("host: string;");
  });
  it("carries TSDoc from descriptions", () => {
    expect(block("Team")).toContain("Needs teams:set-aws-accounts on update");
  });
});

describe("codegen:check (M0-G5)", () => {
  it("the committed src/generated matches a fresh generation", () => {
    expect(diffGenerated(generate())).toEqual([]);
  });
  it("detects drift: a missing, differing and stale file", () => {
    const files = generate();
    const tampered = { ...files, "schemas.ts": `${files["schemas.ts"]}// x`, "new.ts": "x" };
    const d = diffGenerated(tampered);
    expect(d).toContain("differs: schemas.ts");
    expect(d).toContain("missing: new.ts");
    const fewer = { ...files };
    delete fewer["index.ts"];
    expect(diffGenerated(fewer)).toContain("stale: index.ts");
  });
  it("every file has the generated header", () => {
    for (const [name, text] of Object.entries(generate())) {
      expect(
        text.startsWith(
          "// Code generated by tools/codegen from contract/openapi.yaml; DO NOT EDIT.",
        ),
        name,
      ).toBe(true);
    }
  });
  it("reads the contract it was generated from", () => {
    expect(readFileSync(join(CONTRACT_DIR, "openapi.yaml"), "utf8")).toContain("openapi: 3.1.0");
  });
});

import { emitCliTable, kebab } from "./emit-cli-table.js";

describe("CLI table emitter (M1-L1)", () => {
  it("kebab-cases field names, keeping GiB as one word", () => {
    expect(kebab("teamId")).toBe("team-id");
    expect(kebab("maxBudgetUsd")).toBe("max-budget-usd");
    expect(kebab("scratchSizeGiB")).toBe("scratch-size-gib");
  });
  it("lists every CLI operation and none of the non-CLI ones", () => {
    const text = emitCliTable(c);
    expect(text).toContain("CreateTeam:");
    const cli = c.operations.filter((o) => o.cli && !o.cli.startsWith("none"));
    expect([...text.matchAll(/^ {2}\w+: \{"service"/gm)].length).toBe(cli.length);
  });
});

describe("deprecations (WEB-US-46)", () => {
  it("marks deprecated schema fields and schemas @deprecated", () => {
    expect(out).toMatch(/@deprecated[^\n]*\*\/\n\n?export interface TeamCollaboration\b/);
    expect(out).toMatch(/@deprecated[^\n]*\*\/\n\s*mayExposeCollaboration\?: boolean;/);
  });
  it("marks deprecated operations @deprecated in the resource modules", () => {
    const files = generate();
    const text = files["resources/collaboration.ts"] ?? "";
    expect(text).toMatch(/GET \/v1\/teams\/\{teamId\}\/collaboration\n\s*\* @deprecated/);
    expect(files["resources/orchestration.ts"]).not.toContain("@deprecated");
  });
});
