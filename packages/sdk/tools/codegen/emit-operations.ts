import type { Contract } from "./ir.js";

const HEADER = "// Code generated by tools/codegen from contract/openapi.yaml; DO NOT EDIT.\n";

export function emitOperations(c: Contract): string {
  const entries = [...c.operations]
    .sort((a, b) => a.operationId.localeCompare(b.operationId))
    .map((o) => {
      const fields: string[] = [
        `method: ${JSON.stringify(o.method)}`,
        `path: ${JSON.stringify(o.path)}`,
        `pathParams: ${JSON.stringify(o.pathParams)}`,
        `query: ${JSON.stringify(o.queryParams.map((p) => p.name))}`,
        `body: ${!!o.requestBody}`,
        `success: ${JSON.stringify(o.responses.map((r) => r.status))}`,
        `list: ${o.list}`,
        `csv: ${o.csv}`,
        `yaml: ${o.yaml}`,
        `ifMatch: ${JSON.stringify(o.ifMatch)}`,
        `idempotent: ${o.idempotencyKey}`,
      ];
      if (o.reader) fields.push(`reader: ${JSON.stringify(o.reader)}`);
      if (o.versionless) fields.push("versionless: true");
      fields.push(`secretFields: ${JSON.stringify(o.secretFields)}`);
      return `  ${o.operationId}: { ${fields.join(", ")} },`;
    });
  return `${HEADER}import type { OperationDef } from "../core/operation.js";

/** The contract's version (\`info.version\` of the pinned snapshot, WD-8). */
export const CONTRACT_VERSION = ${JSON.stringify(c.version)};

/** Every operation of the contract, keyed by operationId. */
export const operations = {
${entries.join("\n")}
} as const satisfies Record<string, OperationDef>;

/** An operationId of the contract. */
export type OperationId = keyof typeof operations;
`;
}
