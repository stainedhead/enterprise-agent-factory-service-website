import { bodyTypeName, typeOf } from "./emit-schemas.js";
import type { Contract, Node, OperationIR } from "./ir.js";

const HEADER = "// Code generated by tools/codegen from contract/openapi.yaml; DO NOT EDIT.\n";

export const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

interface TreeNode {
  methods: OperationIR[];
  children: Map<string, TreeNode>;
}

function successType(
  o: OperationIR,
  schemas: Record<string, Node>,
): { type: string; kind: string } {
  const ok = o.responses.filter((r) => r.schema && r.status !== 204);
  if (o.yaml) return { type: "string", kind: "promise" };
  if (o.list) {
    const r = ok[0];
    let s: Node = r?.schema;
    if (s?.$ref) s = schemas[s.$ref.split("/").pop() as string];
    const item = typeOf(s.properties.items.items, false);
    return { type: item, kind: o.csv ? "pagedCsv" : "paged" };
  }
  const types = [...new Set(ok.map((r) => typeOf(r.schema, false)))];
  const has204 = o.responses.some((r) => r.status === 204);
  if (types.length === 0) return { type: "void", kind: "promise" };
  const t = types.join(" | ") + (has204 ? " | void" : "");
  return { type: t, kind: o.csv ? "report" : "promise" };
}

function queryOpts(o: OperationIR, schemas: Record<string, Node>): string {
  void schemas;
  const props = o.queryParams.map((p) => {
    return `${/^[A-Za-z_$][\w$]*$/.test(p.name) ? p.name : JSON.stringify(p.name)}${p.required ? "" : "?"}: ${typeOf(p.schema, false)}`;
  });
  return props.length === 0 ? "CallOptions" : `CallOptions & { ${props.join("; ")} }`;
}

function emitMethod(o: OperationIR, c: Contract, indent: string): string {
  const params: string[] = [];
  const argNames: string[] = [];
  o.pathParams.forEach((p, i) => {
    const last = i === o.pathParams.length - 1;
    params.push(`${p}: ${last && o.ifMatch !== "none" ? "string | Versioned" : "string"}`);
    argNames.push(p);
  });
  if (o.requestBody) {
    const t = bodyTypeName(o.requestBody.schema, c.schemas);
    params.push(`body${o.requestBody.required ? "" : "?"}: ${t}`);
  }
  params.push(`opts?: ${queryOpts(o, c.schemas)}`);
  const { type, kind } = successType(o, c.schemas);
  const ret =
    kind === "paged"
      ? `Paginated<${type}>`
      : kind === "pagedCsv"
        ? `PaginatedCsv<${type}>`
        : kind === "report"
          ? `ReportCall<${type}>`
          : `Promise<${type}>`;
  const args = `{ path: [${argNames.join(", ")}]${o.requestBody ? ", body" : ""} }`;
  const fn =
    kind === "paged" || kind === "pagedCsv" ? "paginate" : kind === "report" ? "report" : "call";
  const generic = fn === "call" || fn === "report" ? `<${type}>` : `<${type}>`;
  const docText = `${o.summary}${o.permission ? ` (requires \`${o.permission}\`)` : ""}. ${o.method} ${o.path}`;
  const dep = o.deprecated
    ? `\n${indent} * @deprecated Kept until 2.0.0; see the API contract for the successor operation.`
    : "";
  return `${indent}/** ${docText.replace(/\*\//g, "*\\/")}${dep} */\n${indent}${o.sdk.method}(${params.join(", ")}): ${ret} {\n${indent}  return core.${fn}${generic}(${JSON.stringify(o.operationId)}, ${args}, opts);\n${indent}},`;
}

function emitTree(n: TreeNode, c: Contract, indent: string): string {
  const parts: string[] = [];
  for (const o of n.methods) parts.push(emitMethod(o, c, indent));
  for (const [name, child] of n.children) {
    parts.push(`${indent}${name}: {\n${emitTree(child, c, `${indent}  `)}\n${indent}},`);
  }
  return parts.join("\n");
}

export interface ModuleInfo {
  module: string;
  fn: string;
  /** Facade path: ["teams"] or ["admin", "settings"]. */
  facade: string[];
}

export function modulesOf(c: Contract): ModuleInfo[] {
  const seen = new Map<string, ModuleInfo>();
  for (const o of c.operations) {
    if (seen.has(o.module)) continue;
    const ns = o.sdk.namespace;
    seen.set(o.module, {
      module: o.module,
      fn: camel(o.module),
      facade: ns[0] === "admin" ? ["admin", ns[1] as string] : [ns[0] as string],
    });
  }
  return [...seen.values()].sort((a, b) => a.module.localeCompare(b.module));
}

export function emitResourceModules(c: Contract): Record<string, string> {
  const files: Record<string, string> = {};
  const schemaNames = new Set(Object.keys(c.schemas));
  for (const m of modulesOf(c)) {
    const ops = c.operations.filter((o) => o.module === m.module);
    const rootDepth = m.facade.length;
    const root: TreeNode = { methods: [], children: new Map() };
    for (const o of ops) {
      let node = root;
      for (const seg of o.sdk.namespace.slice(rootDepth)) {
        let next = node.children.get(seg);
        if (!next) {
          next = { methods: [], children: new Map() };
          node.children.set(seg, next);
        }
        node = next;
      }
      if (
        node.children.has(o.sdk.method) ||
        node.methods.some((x) => x.sdk.method === o.sdk.method)
      ) {
        throw new Error(`SDK name collision: ${o.sdk.namespace.join(".")}.${o.sdk.method}`);
      }
      node.methods.push(o);
    }
    const checkNames = (n: TreeNode, path: string) => {
      for (const k of n.children.keys()) {
        if (n.methods.some((x) => x.sdk.method === k))
          throw new Error(`SDK name collision at ${path}.${k}`);
      }
      for (const [k, ch] of n.children) checkNames(ch, `${path}.${k}`);
    };
    checkNames(root, m.module);
    const body = emitTree(root, c, "    ");
    const used = [...new Set(body.match(/\b[A-Z][A-Za-z0-9]*\b/g) ?? [])].filter((x) =>
      schemaNames.has(x),
    );
    const schemaImport =
      used.length > 0 ? `import type { ${used.sort().join(", ")} } from "../schemas.js";\n` : "";
    files[`resources/${m.module}.ts`] =
      `${HEADER}import type { AfsClient } from "../../core/client.js";
import type { CallOptions, Paginated, PaginatedCsv, ReportCall, Versioned } from "../../core/types.js";
${schemaImport}
/** Operations of the \`${m.facade.join(".")}\` namespace. */
export function ${m.fn}(core: AfsClient) {
  return {
${body}
  };
}
`;
  }
  return files;
}

export function emitIndex(c: Contract): string {
  const mods = modulesOf(c);
  const imports = mods
    .map((m) => `import { ${m.fn} } from "./resources/${m.module}.js";`)
    .join("\n");
  const reexports = mods
    .map((m) => `export { ${m.fn} } from "./resources/${m.module}.js";`)
    .join("\n");
  const top = mods.filter((m) => m.facade[0] !== "admin");
  const admin = mods.filter((m) => m.facade[0] === "admin");
  return `${HEADER}import { AfsClient, type AfsClientOptions } from "../core/client.js";
${imports}

export * from "./schemas.js";
export { CONTRACT_VERSION, type OperationId, operations } from "./operations.js";
${reexports}

/** The full SDK surface: every operation of the contract (SDK-1). Not tree-shakeable; use the module factories for that. */
export function createAfs(options: AfsClientOptions) {
  const core = new AfsClient(options);
  return {
    core,
${top.map((m) => `    ${m.facade[0]}: ${m.fn}(core),`).join("\n")}
    admin: {
${admin.map((m) => `      ${m.facade[1]}: ${m.fn}(core),`).join("\n")}
    },
  };
}

/** The object returned by {@link createAfs}. */
export type Afs = ReturnType<typeof createAfs>;
`;
}
