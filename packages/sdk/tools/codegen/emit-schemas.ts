import type { Contract, Node } from "./ir.js";

const HEADER = "// Code generated by tools/codegen from contract/openapi.yaml; DO NOT EDIT.\n";

function doc(text: unknown, indent: string, deprecated = false): string {
  const hasText = typeof text === "string" && text.trim() !== "";
  if (!hasText && !deprecated) return "";
  const lines = hasText ? (text as string).trim().replace(/\*\//g, "*\\/").split("\n") : [];
  if (deprecated)
    lines.push("@deprecated Kept until 2.0.0; see the API contract for the successor.");
  return `${indent}/** ${lines.join(`\n${indent} * `)} */\n`;
}

const q = (s: string) => JSON.stringify(s);

/** Maps a schema node to a TypeScript type expression. `input` drops readOnly properties of objects. */
export function typeOf(n: Node, input: boolean, indent = ""): string {
  if (!n || typeof n !== "object") return "unknown";
  if (typeof n.$ref === "string") return n.$ref.split("/").pop() as string;
  if (Array.isArray(n.allOf)) return n.allOf.map((x: Node) => typeOf(x, input, indent)).join(" & ");
  if (Array.isArray(n.oneOf)) {
    return [...new Set(n.oneOf.map((x: Node) => typeOf(x, input, indent)))].join(" | ");
  }
  if (Array.isArray(n.anyOf)) return n.anyOf.map((x: Node) => typeOf(x, input, indent)).join(" | ");
  const types: string[] = Array.isArray(n.type) ? n.type : n.type ? [n.type] : [];
  const nullable = types.includes("null");
  const real = types.filter((t) => t !== "null");
  let base: string;
  if (Array.isArray(n.enum) && real.includes("string")) {
    const vals = n.enum.filter((v: unknown) => v !== null).map((v: string) => q(v));
    base = `${vals.join(" | ")} | (string & {})`;
    if (vals.length === 0) base = "string";
  } else if (real.length === 0) {
    base =
      types.length === 1 && nullable
        ? "null"
        : n.properties
          ? objectType(n, input, indent)
          : "unknown";
  } else {
    base = real
      .map((t) => {
        switch (t) {
          case "string":
            return "string";
          case "integer":
          case "number":
            return "number";
          case "boolean":
            return "boolean";
          case "array": {
            const it = typeOf(n.items, input, indent);
            return /[|&]/.test(it) && !it.startsWith("(") ? `(${it})[]` : `${it}[]`;
          }
          case "object":
            return objectType(n, input, indent);
          default:
            return "unknown";
        }
      })
      .join(" | ");
  }
  return nullable && base !== "null" ? `${base} | null` : base;
}

function objectType(n: Node, input: boolean, indent: string): string {
  const props: Record<string, Node> = n.properties ?? {};
  const keys = Object.keys(props);
  if (keys.length === 0) {
    if (n.additionalProperties && typeof n.additionalProperties === "object") {
      return `Record<string, ${typeOf(n.additionalProperties, input, indent)}>`;
    }
    return "Record<string, unknown>";
  }
  const required = new Set<string>(n.required ?? []);
  const inner = `${indent}  `;
  const lines = keys
    .filter((k) => !(input && props[k]?.readOnly === true))
    .map((k) => {
      const p = props[k];
      const ro = !input && p.readOnly === true ? "readonly " : "";
      const opt = required.has(k) ? "" : "?";
      return `${doc(p.description, inner, p.deprecated === true)}${inner}${ro}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : q(k)}${opt}: ${typeOf(p, input, inner)};`;
    });
  const extra = n.additionalProperties === true ? [`${inner}[key: string]: unknown;`] : [];
  return `{\n${[...lines, ...extra].join("\n")}\n${indent}}`;
}

export function hasReadOnly(n: Node): boolean {
  return Object.values<Node>(n?.properties ?? {}).some((p) => p.readOnly === true);
}

/** Name of the body type for an operation request body. */
export function bodyTypeName(schema: Node, schemas: Record<string, Node>): string {
  if (typeof schema?.$ref === "string") {
    const name = schema.$ref.split("/").pop() as string;
    return hasReadOnly(schemas[name]) ? `${name}Input` : name;
  }
  return typeOf(schema, true);
}

export function emitSchemas(c: Contract): string {
  const out: string[] = [HEADER];
  out.push(
    "declare const moneyBrand: unique symbol;\n",
    "/** USD amount as a decimal string with at most 6 fraction digits; never a number. */\nexport type Money = string & { readonly [moneyBrand]: true };\n",
  );
  const inputs = new Set<string>();
  for (const o of c.operations) {
    const ref: string | undefined = o.requestBody?.schema?.$ref;
    if (ref) {
      const name = ref.split("/").pop() as string;
      if (hasReadOnly(c.schemas[name])) inputs.add(name);
    }
  }
  for (const name of Object.keys(c.schemas).sort()) {
    if (name === "Money") continue;
    const s = c.schemas[name];
    const t = typeOf(s, false);
    const isObj = t.startsWith("{") && !s.allOf;
    out.push(
      doc(s.description ?? `${name} (OpenAPI schema \`${name}\`).`, "", s.deprecated === true),
      isObj ? `export interface ${name} ${t}\n` : `export type ${name} = ${t};\n`,
    );
    if (inputs.has(name)) {
      out.push(
        `/** Writable fields of ${name} (read-only fields omitted). */\nexport type ${name}Input = ${typeOf(s, true)};\n`,
      );
    }
  }
  return out.join("\n");
}
